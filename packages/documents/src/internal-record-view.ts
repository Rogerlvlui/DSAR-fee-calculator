// ---------------------------------------------------------------------------
// Footer (unchanged since 07-01)
// ---------------------------------------------------------------------------

// PRD §10.5(a)'s footer field list, transcribed by name (packId, packVersion,
// engineVersion, lawyerName, qualification, date) per this plan's own field
// naming.
export interface InternalRecordFooter {
  packId: string;
  packVersion: string;
  engineVersion: string;
  lawyerName: string;
  qualification: string;
  date: string;
}

// PRD §10.5(a)'s footer text, quoted verbatim (including the emphasis
// markers the PRD's own blockquote carries around "AI-drafted"), with its
// six interpolation points left as named placeholders substituted by
// renderInternalRecordFooter below. The wording itself is never altered —
// only the six values are supplied by the caller.
export const INTERNAL_RECORD_FOOTER_TEMPLATE =
  "Prepared with the DSAR Fee Assessment tool. Rule pack {packId} {packVersion}. " +
  "Figures computed by rule engine {engineVersion}; paragraphs marked *AI-drafted* " +
  "were generated by a language model from those figures. Reviewed and signed off " +
  "by {lawyerName}, {qualification}, on {date}. Not legal advice to any third party.";

// WR-01 (07-REVIEW.md) — String.prototype.replace's special replacement
// patterns ($&, $`, $', $$, $<name>) are interpreted in the REPLACEMENT
// argument even when the search argument is a plain string, not a RegExp.
// `footer.qualification` (and, in principle, any other footer field) is
// free text a lawyer types at sign-off time, so a value containing e.g.
// "$&" or "$$" would otherwise silently substitute the matched placeholder
// text or a literal "$" into the rendered footer with no error raised —
// exactly the class of silent defect this evidentiary document cannot
// tolerate. split("{x}").join(value) inserts every value literally, with no
// special-pattern interpretation at all.
function substitutePlaceholder(template: string, placeholder: string, value: string): string {
  return template.split(placeholder).join(value);
}

// Substitutes every placeholder in INTERNAL_RECORD_FOOTER_TEMPLATE — the
// returned string carries no unsubstituted placeholder token for any
// well-formed InternalRecordFooter, and every value is inserted literally
// regardless of `$`-bearing content.
export function renderInternalRecordFooter(footer: InternalRecordFooter): string {
  let rendered = INTERNAL_RECORD_FOOTER_TEMPLATE;
  rendered = substitutePlaceholder(rendered, "{packId}", footer.packId);
  rendered = substitutePlaceholder(rendered, "{packVersion}", footer.packVersion);
  rendered = substitutePlaceholder(rendered, "{engineVersion}", footer.engineVersion);
  rendered = substitutePlaceholder(rendered, "{lawyerName}", footer.lawyerName);
  rendered = substitutePlaceholder(rendered, "{qualification}", footer.qualification);
  rendered = substitutePlaceholder(rendered, "{date}", footer.date);
  return rendered;
}

